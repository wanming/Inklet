import AppKit
import Foundation

/// Reads a copy from the pasteboard for clipboard history and writes a history item back.
@MainActor
public enum ClipboardPasteboard {
    /// Markers apps add to copies that clipboard managers should not keep (nspasteboard.org):
    /// passwords from password managers, temporary copies and generated content.
    public static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType"),
    ]

    /// What the person copied, or nil for content history skips: private or temporary copies,
    /// copied files (not supported yet), and empty text.
    public static func capture(
        from pasteboard: NSPasteboard,
        sourceApplication: NSRunningApplication?
    ) -> ClipboardCapture? {
        let types = Set(pasteboard.types ?? [])
        guard !types.isEmpty,
              types.isDisjoint(with: ignoredTypes),
              !types.contains(.fileURL)
        else {
            return nil
        }

        let content: ClipboardCapture.Content
        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            content = .text(text)
        } else if let image = imageContent(from: pasteboard, types: types) {
            content = image
        } else {
            return nil
        }

        return ClipboardCapture(
            content: content,
            sourceApplicationName: sourceApplication?.localizedName,
            sourceBundleIdentifier: sourceApplication?.bundleIdentifier
        )
    }

    /// Puts a history item on the pasteboard: text as plain text, images as PNG and TIFF.
    @discardableResult
    public static func write(
        _ item: ClipboardHistoryItem,
        imageURL: URL?,
        to pasteboard: NSPasteboard
    ) -> Bool {
        switch item.kind {
        case .text:
            guard let text = item.text else {
                return false
            }
            pasteboard.clearContents()
            return pasteboard.setString(text, forType: .string)
        case .image:
            guard let imageURL,
                  let pngData = try? Data(contentsOf: imageURL)
            else {
                return false
            }
            pasteboard.clearContents()
            pasteboard.declareTypes([.png, .tiff], owner: nil)
            let didWritePNG = pasteboard.setData(pngData, forType: .png)
            if let tiffData = NSBitmapImageRep(data: pngData)?.tiffRepresentation {
                pasteboard.setData(tiffData, forType: .tiff)
            }
            return didWritePNG
        }
    }

    private static func imageContent(
        from pasteboard: NSPasteboard,
        types: Set<NSPasteboard.PasteboardType>
    ) -> ClipboardCapture.Content? {
        let data: Data?
        if types.contains(.png) {
            data = pasteboard.data(forType: .png)
        } else if types.contains(.tiff) {
            data = pasteboard.data(forType: .tiff)
        } else {
            data = nil
        }
        guard let data,
              data.count <= ClipboardHistoryStore.maximumImageBytes * 4,
              let representation = NSBitmapImageRep(data: data)
        else {
            return nil
        }

        let pngData: Data
        if types.contains(.png) {
            pngData = data
        } else if let converted = representation.representation(using: .png, properties: [:]) {
            pngData = converted
        } else {
            return nil
        }
        return .image(
            pngData: pngData,
            pixelWidth: representation.pixelsWide,
            pixelHeight: representation.pixelsHigh
        )
    }
}
